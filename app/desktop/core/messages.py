_FALLBACK_LANGUAGE: str = "es"


def translate(language: str, key: str, **params: object) -> str:
    """
    Return a backend message in the requested language.

    Args:
        language: Language code, falling back to Spanish when unknown.
        key: Message identifier.
        **params: Values interpolated into the message.

    Returns:
        The formatted message.
    """
    catalog: dict[str, str] = _MESSAGES.get(language, _MESSAGES[_FALLBACK_LANGUAGE])
    template: str = catalog.get(key, _MESSAGES[_FALLBACK_LANGUAGE].get(key, key))
    return template.format(**params)

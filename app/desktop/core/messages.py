"""
Localized texts for notifications generated by the backend.
"""

# Standard library
from __future__ import annotations

_MESSAGES: dict[str, dict[str, str]] = {
    "es": {
        "task_reminder_title": "¡Es hora!",
        "task_reminder_text": "\"{title}\" — era para {when}",
        "task_reminder_text_undated": "\"{title}\"",
        "habit_reminder_title": "Completa tu hábito: {name}",
        "habit_reminder_text": "Racha de {streak} en juego. Márcalo hoy para no perderla.",
    },
    "en": {
        "task_reminder_title": "It's time!",
        "task_reminder_text": "\"{title}\" — was due {when}",
        "task_reminder_text_undated": "\"{title}\"",
        "habit_reminder_title": "Complete your habit: {name}",
        "habit_reminder_text": "A streak of {streak} is at stake. Check it today to keep it.",
    },
}

_FALLBACK_LANGUAGE: str = "es"


def translate(language: str, key: str, **params: object) -> str:
    """
    Return a backend message in the requested language.

    Args:
        language: Language code, falling back to Spanish when unknown.
        key: Message identifier.
        **params: Values interpolated into the message.

    Returns:
        The formatted message.
    """
    catalog: dict[str, str] = _MESSAGES.get(language, _MESSAGES[_FALLBACK_LANGUAGE])
    template: str = catalog.get(key, _MESSAGES[_FALLBACK_LANGUAGE].get(key, key))
    return template.format(**params)
